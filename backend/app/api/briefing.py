"""Executive S&OP briefing as a PDF (reportlab)."""
from __future__ import annotations

import io
from typing import Any, Dict, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def _gbp(v: Any) -> str:
    return "-" if v is None else f"£{float(v):,.0f}"


def _n(v: Any) -> str:
    return "-" if v is None else f"{float(v):,.0f}"


def _table(rows, widths=None) -> Table:
    t = Table(rows, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e293b")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
    ]))
    return t


def build_pdf(ctx: Dict[str, Any], safety: Optional[Dict[str, Any]], otif_out: Dict[str, Any]) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm)
    st = getSampleStyleSheet()
    c = ctx["cycle"]
    touch = 100 * c["autopilot_approved_skus"] / max(c["in_scope_skus"], 1)
    story = [
        Paragraph("S&amp;OP Executive Briefing", st["Title"]),
        Paragraph(f"Cycle cutoff {c['cutoff']} | planning from {c['first_month']} | "
                  f"{'committed' if c['committed'] else 'consensus in progress'}", st["Normal"]),
        Spacer(1, 6 * mm), Paragraph("Headline", st["Heading2"]),
        _table([["Metric", "Value"],
                ["Active items (in scope / catalogue)", f"{c['in_scope_skus']:,} / {c['total_catalog_skus']:,}"],
                ["Touchless autopilot", f"{touch:.1f}% ({c['autopilot_approved_skus']:,} items)"],
                ["Exception queue (decided / total)", f"{c['decided']} / {c['exceptions_requiring_review']}"],
                ["Planner-led items", f"{c['planner_led_skus']:,}"],
                ["Planned value vs baseline", f"{_gbp(c['planned_value_gbp'])} vs {_gbp(c['baseline_value_gbp'])}"],
                ["OOS / Buy Box alerts in queue", str(c["critical_alerts"])],
                ["OTIF exposure (B2B)", f"{len(otif_out['rows'])} item-months, {_gbp(otif_out['total_penalty_gbp'])}"]],
               [90 * mm, 85 * mm]),
    ]
    if ctx["quality_warnings"]:
        story += [Spacer(1, 4 * mm), Paragraph("Data quality", st["Heading2"])]
        for w in ctx["quality_warnings"]:
            story.append(Paragraph(f"{w['channel']} {w['month']}: {w['imputed_share'] * 100:.0f}% of actuals imputed "
                                   f"({w['items']:,} items); masked as missing in this cycle.", st["Normal"]))
    story += [Spacer(1, 4 * mm), Paragraph("Top exceptions by value at risk", st["Heading2"]),
              _table([["Item", "Channel", "ABC", "Baseline", "ML plan", "Value delta", "Risk"]] +
                     [[str(r["item_id"]), r["channel"], str(r["abc_category"]), _n(r["baseline_h"]), _n(r["final_h"]),
                       _gbp(r["value_delta_gbp"]), r["risk_type"]] for r in ctx["exception_queue_top"][:12]])]
    if ctx["phasing_first_month"]:
        story += [Spacer(1, 4 * mm), Paragraph("Demand vs expected deliveries (first planning month)", st["Heading2"]),
                  _table([["Channel", "Demand", "Expected delivery", "Booked"]] +
                         [[r["channel"], _n(r["demand"]), _n(r["expected_delivery"]), _n(r["booked"])] for r in ctx["phasing_first_month"]])]
    if safety:
        a = safety["a_items"]
        red = a["reduction_pct"]
        story += [Spacer(1, 4 * mm), Paragraph("Inventory coupling (A-items)", st["Heading2"]),
                  Paragraph(f"Dynamic safety stock {_n(a['ss_dynamic_units'])} units vs static {_n(a['ss_static_units'])}; "
                            f"holding cost {_gbp(a['holding_dynamic_gbp'])} vs {_gbp(a['holding_static_gbp'])} "
                            f"({'-' if red is None else f'{red * 100:.1f}%'} change, target {safety['target_reduction_pct'] * 100:.0f}%). "
                            + (f"Back-tested service (A-items, h1): dynamic {safety['service_backtest']['service_dynamic'] * 100:.1f}% vs "
                               f"static {safety['service_backtest']['service_static'] * 100:.1f}% (target 98%)."
                               if safety.get("service_backtest") else ""), st["Normal"])]
    story += [Spacer(1, 6 * mm), Paragraph("Generated by the Demand Forecast Co-Pilot from the current cycle artifacts and the audit ledger.", st["Italic"])]
    doc.build(story)
    return buf.getvalue()
