import React, { useCallback, useEffect, useState } from "react";
import { Play, RefreshCw, CheckCircle2, XCircle, Circle, PauseCircle, Bot, X } from "lucide-react";
import { api } from "../services/api";
import { fmtNum, monthLabel } from "../lib/format";
import { Panel, Stat, DataTable, ErrorNote } from "../components/ui";
import SchedulePanel from "../components/SchedulePanel";

const STATUS_STYLE = {
  RUNNING: "bg-sky-900 text-sky-200", AWAITING_REVIEW: "bg-amber-900 text-amber-200", SUCCEEDED: "bg-emerald-900 text-emerald-200",
  COMMITTED: "bg-emerald-900 text-emerald-200", FAILED: "bg-rose-900 text-rose-200",
};
const NODE_LABEL = {
  ingest_validate: "Data quality check",
  base_inference: "Forecast refresh",
  reconcile: "Product reconciliation",
  phasing: "Order-book phasing",
  rules_triage: "Planner triage",
  bands_safety: "Risk bands & stock",
  narrative: "Exception narratives",
  agent_actions: "Planner actions",
  human_review: "Human review",
};
const ACTION_LABEL = {
  review_exception: "Review exception",
  apply_autopilot: "Review autopilot",
  recompute_forecast: "Check forecast",
  review_phasing: "Review supply",
  mitigate_otif: "Mitigate OTIF",
};
const warningText = (w) => (typeof w === "string" ? w
  : `Incomplete actuals: ${w.channel} for ${monthLabel(w.month)} is ${(w.imputed_share * 100).toFixed(0)}% imputed across ${w.items.toLocaleString("en-GB")} items.`);

function NodeTrack({ nodes, run }) {
  const done = Object.fromEntries((run.steps || []).map((s) => [s.node, s]));
  const reached = run.status === "AWAITING_REVIEW" || run.status === "COMMITTED";
  return (
    <ol className="flex flex-wrap gap-2 mt-3">
      {nodes.map((n) => {
        const s = done[n];
        const review = n === "human_review";
        let icon = <Circle className="h-3.5 w-3.5 text-slate-600" />;
        if (s && s.status === "ok") icon = <CheckCircle2 className="h-3.5 w-3.5 text-emerald-400" />;
        if (s && s.status === "failed") icon = <XCircle className="h-3.5 w-3.5 text-rose-400" />;
        if (review && reached) icon = <PauseCircle className="h-3.5 w-3.5 text-amber-400" />;
        return (
          <li key={n} title={s ? (s.error || JSON.stringify(s.detail)) : ""}
            className="flex items-center gap-1.5 text-[11px] bg-slate-950 border border-slate-800 rounded-md px-2 py-1 text-slate-300">
            {icon} {NODE_LABEL[n] || n.replace(/_/g, " ")} {s && <span className="text-slate-500 font-mono">{s.seconds}s</span>}
          </li>
        );
      })}
    </ol>
  );
}

export default function OperationsPage({ role, onReloaded, onNavigateAction }) {
  const [runs, setRuns] = useState(null);
  const [agentActions, setAgentActions] = useState(null);
  const [quality, setQuality] = useState(null);
  const [detail, setDetail] = useState(null);
  const [error, setError] = useState(null);
  const [busy, setBusy] = useState(false);
  const isAdmin = role === "admin";

  const load = useCallback(async () => {
    try {
      const [r, aa, q] = await Promise.all([api.runs(), api.cycleAgentActions(), api.summary()]);
      setRuns(r);
      setAgentActions(aa);
      setQuality(q);
    } catch (e) {
      setError(e.message);
    }
  }, []);

  useEffect(() => { load(); }, [load]);
  const running = runs && runs.runs.some((r) => r.status === "RUNNING");
  useEffect(() => {
    if (!running) return undefined;
    const t = setInterval(load, 3000);
    return () => clearInterval(t);
  }, [running, load]);
  const wasRunning = React.useRef(false);
  useEffect(() => {
    if (wasRunning.current && !running) {
      onReloaded();
      window.dispatchEvent(new Event("sop:notifications-refresh"));
    }
    wasRunning.current = running;
  }, [running, onReloaded]);

  const start = async (fn) => {
    setBusy(true);
    setError(null);
    try { await fn(); await load(); } catch (e) { setError(e.message); } finally { setBusy(false); }
  };

  return (
    <div className="px-8 py-6 space-y-6" data-testid="operations-page">
      <ErrorNote error={error} />
      <SchedulePanel isAdmin={isAdmin} />
      <Panel title="Monthly cycle agent actions" testId="cycle-agent-actions-panel"
        subtitle={agentActions ? `Generated for planning from ${agentActions.first_month}; ${agentActions.summary?.otif_items_at_risk || 0} OTIF items at risk.` : "Planner-ready outputs are generated by the monthly cycle."}>
        {!agentActions && <div className="text-xs text-slate-500">No agent action artifact is available yet.</div>}
        {agentActions && (
          <div className="space-y-4">
            <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
              <Stat label="Actions" value={fmtNum(agentActions.actions.length)} tone="text-indigo-300" />
              <Stat label="Autopilot ideas" value={fmtNum(agentActions.summary?.autopilot_actions)} />
              <Stat label="Forecast checks" value={fmtNum(agentActions.summary?.dynamic_forecast_candidates)} />
              <Stat label="Scenario prompts" value={fmtNum(agentActions.scenario_prompts?.length)} />
            </div>
            <DataTable testId="agent-actions-table" rows={agentActions.actions.slice(0, 8)} empty="No agent actions available."
              columns={[
                { key: "priority", label: "Priority", render: (r) => <span className={r.priority === "high" ? "text-rose-300" : "text-amber-300"}>{r.priority}</span> },
                { key: "type", label: "Type", render: (r) => ACTION_LABEL[r.type] || r.type.replace(/_/g, " ") },
                { key: "title", label: "Action" },
                { key: "detail", label: "Why" },
                { key: "open", label: "", render: (r) => onNavigateAction ? (
                  <button data-testid={`agent-action-open-${r.id}`} onClick={() => onNavigateAction(r)}
                    className="px-2 py-1 bg-slate-800 hover:bg-slate-700 border border-slate-700 rounded text-[10px] font-semibold text-white">Open</button>
                ) : null },
              ]} />
            {agentActions.scenario_prompts.length > 0 && (
              <div className="bg-slate-950 border border-slate-800 rounded-lg p-3">
                <div className="text-xs font-semibold text-slate-200 flex items-center gap-1.5 mb-2"><Bot className="h-3.5 w-3.5 text-indigo-400" /> Suggested scenario prompts</div>
                <div className="space-y-1">{agentActions.scenario_prompts.map((p) => (
                  <button key={p} type="button" onClick={() => onNavigateAction && onNavigateAction({ type: "scenario_prompt", prompt: p })}
                    className="block w-full text-left text-[11px] text-slate-400 hover:text-indigo-200">{p}</button>
                ))}</div>
              </div>
            )}
          </div>
        )}
      </Panel>
      <Panel title="Monthly cycle orchestration" testId="cycle-runs-panel"
        subtitle="Refreshes demand forecasts, reconciles products, applies planning rules, updates risk bands, writes planner actions, then pauses for human review. A failed guard halts the run; nothing after it is published."
        right={isAdmin && (
          <button data-testid="run-cycle-btn" disabled={busy || running} onClick={() => start(api.runCycle)}
            className="px-3 py-2 bg-indigo-600 hover:bg-indigo-500 disabled:opacity-40 rounded-lg text-xs font-semibold flex items-center gap-2">
            {running ? <RefreshCw className="h-4 w-4 animate-spin" /> : <Play className="h-4 w-4" />} {running ? "Running..." : "Run monthly cycle"}
          </button>
        )}>
        {runs && runs.runs.length === 0 && <div className="text-xs text-slate-500" data-testid="no-runs">No pipeline run recorded yet.</div>}
        <div className="space-y-3">
          {runs && runs.runs.map((r) => (
            <div key={r.id} data-testid={`run-${r.id}`} className="bg-slate-950/60 border border-slate-800 rounded-lg p-3">
              <button type="button" data-testid={`run-open-${r.id}`}
                onClick={() => api.runDetail(r.id).then(setDetail).catch((e) => setError(e.message))}
                className="w-full text-left">
                <div className="flex flex-wrap items-center gap-3 text-xs">
                  <span className={`px-2 py-0.5 rounded text-[10px] font-semibold ${STATUS_STYLE[r.status] || "bg-slate-800"}`} data-testid="run-status">{r.status}</span>
                  <span className="text-slate-200 font-semibold">{r.kind === "monthly_cycle" ? "Monthly cycle" : "Pipeline run"}</span>
                  <span className="text-slate-500">{new Date(r.started_at).toLocaleString("en-GB")} by {r.started_by}</span>
                  {r.error && <span className="text-rose-300">{r.error}</span>}
                  <span className="ml-auto text-[10px] text-indigo-300">Details</span>
                </div>
              </button>
              {r.kind === "monthly_cycle" && <NodeTrack nodes={runs.nodes} run={r} />}
              {(r.steps || []).filter((s) => s.status === "failed").map((s) => (
                <div key={s.node} className="text-[11px] text-rose-300 mt-2">{s.node}: {s.error}</div>
              ))}
            </div>
          ))}
        </div>
      </Panel>
      {detail && (
        <Panel title={`Run detail — ${detail.kind === "monthly_cycle" ? "Monthly cycle" : "Pipeline run"}`} testId="run-detail-panel"
          right={<button data-testid="run-detail-close" onClick={() => setDetail(null)} className="text-slate-400 hover:text-white"><X className="h-4 w-4" /></button>}>
          <div className="space-y-3">
            <div className="flex flex-wrap gap-3 text-xs text-slate-400">
              <span>Status <strong className="text-slate-200">{detail.status}</strong></span>
              <span>Started <strong className="text-slate-200">{new Date(detail.started_at).toLocaleString("en-GB")}</strong></span>
              <span>By <strong className="text-slate-200">{detail.started_by}</strong></span>
              {detail.finished_at && <span>Finished <strong className="text-slate-200">{new Date(detail.finished_at).toLocaleString("en-GB")}</strong></span>}
            </div>
            {detail.error && <div className="text-[11px] text-rose-300 bg-rose-950/30 border border-rose-800 rounded-lg p-2">{detail.error}</div>}
            <div className="space-y-2">
              {(detail.steps || []).map((s, i) => (
                <div key={`${s.node}-${i}`} data-testid={`run-step-${s.node}`}
                  className={`rounded-lg border p-2 text-[11px] ${s.status === "failed" ? "border-rose-800 bg-rose-950/20" : "border-slate-800 bg-slate-950/60"}`}>
                  <div className="flex items-center gap-2">
                    {s.status === "failed" ? <XCircle className="h-3.5 w-3.5 text-rose-400" /> : <CheckCircle2 className="h-3.5 w-3.5 text-emerald-400" />}
                    <span className="font-semibold text-slate-200">{NODE_LABEL[s.node] || s.node}</span>
                    <span className="text-slate-500 font-mono">{s.seconds}s</span>
                    {s.rerun && <span className="px-1.5 py-0.5 bg-indigo-950 border border-indigo-800 text-indigo-200 rounded text-[9px] font-semibold">RE-RUN</span>}
                    {isAdmin && s.status === "failed" && (
                      <button data-testid={`rerun-node-${s.node}`} disabled={busy}
                        onClick={() => start(() => api.rerunNode(detail.id, s.node).then(() => api.runDetail(detail.id).then(setDetail)))}
                        className="ml-auto px-2 py-1 bg-slate-800 hover:bg-slate-700 border border-slate-700 rounded text-[10px] font-semibold text-white">Re-run node</button>
                    )}
                  </div>
                  {s.error && <div className="text-rose-300 mt-1">{s.error}</div>}
                  {s.detail && <div className="text-slate-400 mt-1 font-mono">{JSON.stringify(s.detail)}</div>}
                </div>
              ))}
            </div>
            <div>
              <div className="text-xs font-semibold text-slate-300 mb-1">Data-quality gate (current cycle)</div>
              {detail.quality_warnings && detail.quality_warnings.length > 0
                ? <ul className="text-[11px] text-amber-200 space-y-0.5">{detail.quality_warnings.map((w) => <li key={`${w.channel}-${w.month}`}>{warningText(w)}</li>)}</ul>
                : <div className="text-[11px] text-emerald-300">No data-quality warnings.</div>}
            </div>
          </div>
        </Panel>
      )}
      <Panel title="Data quality gate" testId="quality-gate-panel"
        subtitle="Warnings from the ingest/validate step of the monthly cycle; the gate halts the run on schema violations.">
        {quality && quality.quality_warnings && quality.quality_warnings.length > 0 ? (
          <ul className="text-[11px] text-amber-200 space-y-0.5">{quality.quality_warnings.map((w) => <li key={`${w.channel}-${w.month}`}>{warningText(w)}</li>)}</ul>
        ) : (
          <div className="text-xs text-emerald-300">No data-quality warnings in the current cycle.</div>
        )}
      </Panel>
    </div>
  );
}
